"""
Live wiring of the deterministic collections next-action engine onto
eh.collections.case.

Operational action and priority keys are stored so managers can search,
sort, and group cases. Their dependencies cover every durable case input;
the Collections nightly refresh advances the time-dependent overdue state.
The human rationale remains a live translated compute so one user's language
is never persisted for every other user.

The optional LLM-enriched narrative is NEVER produced on read. A compute
must not perform synchronous network I/O: with a live provider configured
that would fire a blocking outbound HTTPS POST on every collections case
form/list access and starve the HTTP workers. The provider is therefore
invoked only from the explicit action_eh_ai_refresh_suggestion button,
which writes immutable, attributed and fingerprinted evidence fields.
"""

import dataclasses
import hashlib
import json

from odoo import _, api, fields, models
from odoo.exceptions import AccessError, UserError

from odoo.addons.eh_account_ai_agent.tools import next_action_suggester
from odoo.addons.eh_account_ai_agent.tools.provider_registry import ProviderError

from .control import (
    AI_COLLECTIONS_DEMAND_CAPABILITY,
    AI_COLLECTIONS_DEMAND_CONTEXT,
    AI_COLLECTIONS_EVIDENCE_CAPABILITY,
    AI_COLLECTIONS_EVIDENCE_CONTEXT,
)


_SUGGESTED_ACTIONS = [
    ('no_action_resolved', "No action — resolved"),
    ('review_dispute', "Review dispute"),
    ('monitor_paused_case', "Monitor paused case"),
    ('monitor_payment_plan', "Monitor payment plan"),
    ('escalate_to_manager', "Escalate to manager"),
    ('monitor', "Monitor promise"),
    ('consider_write_off', "Consider write-off"),
    ('refer_to_collections_agency', "Review external agency referral"),
    ('review_demand_letter', "Review demand letter"),
    ('send_demand_letter', "Send demand letter"),
    ('phone_call', "Make phone call"),
    ('first_contact_email', "Send first-contact email"),
    ('manual_review', "Manual review"),
]

_SUGGESTION_DEPENDENCIES = (
    'days_overdue_max', 'total_overdue_amount',
    'has_active_promise', 'broken_promise',
    'action_ids', 'action_ids.contact_made',
    'action_ids.action_type', 'action_ids.action_date',
    'action_ids.promise_amount', 'action_ids.promise_date',
    'action_ids.eh_ai_is_demand_letter',
    'is_resolved', 'stage_id.is_disputed', 'followup_paused',
    'has_active_payment_plan',
    'company_id.eh_ai_collections_writeoff_materiality',
)

_PROTECTED_AI_EVIDENCE_FIELDS = frozenset({
    'eh_ai_suggestion_narrative',
    'eh_ai_narrative_generated_at',
    'eh_ai_narrative_generated_by_id',
    'eh_ai_narrative_provider_key',
    'eh_ai_narrative_source_fingerprint',
    'eh_ai_narrative_stale',
})


class EhCollectionsCase(models.Model):
    _inherit = 'eh.collections.case'

    eh_ai_suggested_action = fields.Selection(
        _SUGGESTED_ACTIONS,
        string="AI suggested action",
        compute='_compute_eh_ai_suggestion', store=True, index=True,
    )
    eh_ai_suggested_priority = fields.Selection(
        [('low', "Low"), ('medium', "Medium"), ('high', "High")],
        string="AI priority",
        compute='_compute_eh_ai_suggestion', store=True, index=True,
    )
    eh_ai_suggestion_rationale = fields.Text(
        string="AI rationale",
        compute='_compute_eh_ai_suggestion_rationale',
        compute_sudo=False,
        store=False,
    )
    eh_ai_suggestion_narrative = fields.Text(
        string="AI suggestion narrative",
        readonly=True, copy=False,
        help="Provider-enriched next-action narrative produced by the "
             "explicit Refresh AI suggestion button. Empty until the "
             "button is pressed; never generated on read so opening a "
             "collections case never triggers a synchronous LLM call.",
    )
    eh_ai_narrative_generated_at = fields.Datetime(
        string="AI narrative generated at",
        readonly=True, copy=False,
    )
    eh_ai_narrative_generated_by_id = fields.Many2one(
        'res.users', string="AI narrative generated by",
        readonly=True, copy=False, ondelete='restrict',
    )
    eh_ai_narrative_provider_key = fields.Char(
        string="AI narrative provider", readonly=True, copy=False,
    )
    eh_ai_narrative_source_fingerprint = fields.Char(
        string="AI narrative source fingerprint",
        readonly=True, copy=False, index=True,
    )
    eh_ai_narrative_stale = fields.Boolean(
        string="AI narrative is stale",
        compute='_compute_eh_ai_narrative_stale', store=True,
        help=(
            "True when current case facts no longer match the immutable "
            "snapshot used for the stored provider narrative."
        ),
    )
    has_active_payment_plan = fields.Boolean(
        string="Active payment plan",
        tracking=True,
        help="Set while a documented payment plan remains active. AI dunning "
             "then recommends monitoring the plan instead of a demand letter.",
    )

    @api.depends(*_SUGGESTION_DEPENDENCIES)
    def _compute_eh_ai_suggestion(self):
        # DETERMINISTIC ONLY. Stored action/priority recompute when case facts
        # change, never through a network provider. Live rationale reads use
        # the separate non-stored compute below; richer provider narrative is
        # produced only by action_eh_ai_refresh_suggestion. Passing the live
        # company provider from either compute would make ordinary reads or
        # dependency recomputes issue blocking outbound HTTPS requests.
        for case in self:
            suggestion = case._eh_deterministic_suggestion()
            case.eh_ai_suggested_action = suggestion.action
            case.eh_ai_suggested_priority = suggestion.priority

    @api.depends(*_SUGGESTION_DEPENDENCIES)
    def _compute_eh_ai_suggestion_rationale(self):
        for case in self:
            suggestion = case._eh_deterministic_suggestion()
            case.eh_ai_suggestion_rationale = suggestion.rationale

    def _eh_deterministic_suggestion(self):
        self.ensure_one()
        return next_action_suggester.suggest(
            self._eh_build_case_snapshot(), provider_key='manual',
        )

    def _eh_build_case_snapshot(self):
        """Map the case onto the helper's CaseSnapshot transport record."""
        self.ensure_one()
        today = fields.Date.context_today(self)
        contacts = self.action_ids.filtered(lambda a: a.contact_made)
        last_action = self.action_ids.sorted(
            key=lambda action: action.action_date,
            reverse=True,
        )[:1]
        last_days = 0
        if last_action:
            local_action_date = fields.Datetime.context_timestamp(
                self, last_action.action_date,
            ).date()
            last_days = max(0, (today - local_action_date).days)
        demand_letters = self.action_ids.filtered(
            lambda action: action.eh_ai_is_demand_letter
        ).sorted('action_date', reverse=True)
        demand_letter_days_ago = None
        if demand_letters:
            local_letter_date = fields.Datetime.context_timestamp(
                self, demand_letters[0].action_date,
            ).date()
            demand_letter_days_ago = max(
                0, (today - local_letter_date).days,
            )
        return next_action_suggester.CaseSnapshot(
            days_overdue=self.days_overdue_max or 0,
            total_overdue=self.total_overdue_amount or 0.0,
            contact_count=len(contacts),
            has_active_promise=bool(self.has_active_promise),
            has_broken_promise=bool(self.broken_promise),
            last_action_type=(last_action.action_type or '') if last_action else '',
            last_action_days_ago=last_days,
            has_demand_letter=bool(demand_letters),
            demand_letter_days_ago=demand_letter_days_ago,
            has_payment_plan=bool(self.has_active_payment_plan),
            is_resolved=bool(self.is_resolved),
            is_disputed=bool(self.stage_id.is_disputed),
            is_paused=bool(self.followup_paused),
            customer_segment='',
            writeoff_materiality=(
                self.company_id.eh_ai_collections_writeoff_materiality or 0.0
            ),
        )

    def _eh_ai_source_fingerprint(self, provider_key):
        """Hash exact durable case facts and provider identity."""
        self.ensure_one()
        payload = {
            'schema': 1,
            'company_id': self.company_id.id,
            'provider_key': provider_key or '',
            'snapshot': dataclasses.asdict(self._eh_build_case_snapshot()),
        }
        encoded = json.dumps(
            payload, sort_keys=True, separators=(',', ':'),
            ensure_ascii=True,
        ).encode('utf-8')
        return hashlib.sha256(encoded).hexdigest()

    @api.depends(
        'eh_ai_suggestion_narrative',
        'eh_ai_narrative_provider_key',
        'eh_ai_narrative_source_fingerprint',
        'days_overdue_max', 'total_overdue_amount',
        'action_ids', 'action_ids.contact_made',
        'action_ids.action_type', 'action_ids.action_date',
        'action_ids.promise_amount', 'action_ids.promise_date',
        'action_ids.eh_ai_is_demand_letter',
        'is_resolved', 'stage_id.is_disputed', 'followup_paused',
        'has_active_payment_plan',
        'company_id.eh_ai_collections_writeoff_materiality',
    )
    def _compute_eh_ai_narrative_stale(self):
        for case in self:
            if not case.eh_ai_suggestion_narrative:
                case.eh_ai_narrative_stale = False
                continue
            provider_key = case.eh_ai_narrative_provider_key
            fingerprint = case.eh_ai_narrative_source_fingerprint
            case.eh_ai_narrative_stale = bool(
                not provider_key
                or not fingerprint
                or fingerprint != case._eh_ai_source_fingerprint(provider_key)
            )

    @api.model_create_multi
    def create(self, vals_list):
        if any(
            _PROTECTED_AI_EVIDENCE_FIELDS.intersection(vals)
            for vals in vals_list
        ):
            raise AccessError(_(
                "AI collections evidence is server-generated and cannot be "
                "supplied when a case is created."
            ))
        return super().create(vals_list)

    def write(self, vals):
        protected = _PROTECTED_AI_EVIDENCE_FIELDS.intersection(vals)
        if protected and self.env.context.get(
            AI_COLLECTIONS_EVIDENCE_CONTEXT,
        ) is not AI_COLLECTIONS_EVIDENCE_CAPABILITY:
            raise AccessError(_(
                "AI collections evidence is server-generated and cannot be "
                "edited directly."
            ))
        return super().write(vals)

    def _apply_followup_level(self, level, source='cron'):
        """Stamp configured automated final notices as demand evidence."""
        target = self
        if level.eh_ai_is_demand_letter:
            target = self.with_context(**{
                AI_COLLECTIONS_DEMAND_CONTEXT:
                    AI_COLLECTIONS_DEMAND_CAPABILITY,
            })
        return super(EhCollectionsCase, target)._apply_followup_level(
            level, source=source,
        )

    def action_eh_ai_refresh_suggestion(self):
        """Explicit user gesture that runs the configured AI provider.

        This is the ONLY place the provider is invoked, because the
        provider may perform outbound network I/O (a blocking HTTPS
        POST). Running it here, on a deliberate button press, keeps that
        call off the read path. This action is manager-only and singleton:
        a crafted multi-record RPC cannot turn one request into sequential
        provider calls. Exact source/provider fingerprints make unchanged
        refreshes idempotent. Missing, manual, failed, malformed, or
        control-suppressed providers leave existing evidence unchanged.
        """
        if len(self) != 1:
            raise UserError(_(
                "Refresh one collections case at a time. Bulk provider "
                "requests are not allowed."
            ))
        if not (
            self.env.su
            or self.env.user.has_group('eh_account_base.group_eh_manager')
        ):
            raise AccessError(_(
                "Only an ERP Heritage accounting manager can refresh an AI "
                "collections narrative."
            ))
        self._eh_check_access('write')
        case = self
        case.flush_recordset([
            'eh_ai_suggestion_narrative',
            'eh_ai_narrative_provider_key',
            'eh_ai_narrative_source_fingerprint',
        ])
        self.env.cr.execute(
            "SELECT id FROM eh_collections_case WHERE id = %s FOR UPDATE",
            [case.id],
        )
        case.invalidate_recordset([
            'eh_ai_suggestion_narrative',
            'eh_ai_narrative_generated_at',
            'eh_ai_narrative_generated_by_id',
            'eh_ai_narrative_provider_key',
            'eh_ai_narrative_source_fingerprint',
            'eh_ai_narrative_stale',
        ])
        company = case.company_id
        provider_key = company.eh_ai_provider_key or 'manual'
        snapshot = case._eh_build_case_snapshot()
        if (
            snapshot.is_resolved
            or snapshot.is_disputed
            or snapshot.is_paused
            or snapshot.has_payment_plan
            or snapshot.has_active_promise
            or snapshot.has_broken_promise
        ):
            raise UserError(_(
                "No AI suggestion was stored: this case is governed by a "
                "recorded workflow control. The existing AI narrative, if "
                "any, is unchanged."
            ))
        fingerprint = case._eh_ai_source_fingerprint(provider_key)
        if (
            case.eh_ai_suggestion_narrative
            and case.eh_ai_narrative_provider_key == provider_key
            and case.eh_ai_narrative_source_fingerprint == fingerprint
        ):
            return True
        try:
            suggestion = next_action_suggester.provider_suggest(
                snapshot,
                provider_key=provider_key,
                provider_config=company.sudo().eh_ai_provider_config or None,
            )
        except ProviderError as exc:
            raise UserError(_(
                "No AI suggestion was stored: %(reason)s The existing "
                "AI narrative, if any, is unchanged.",
                reason=str(exc),
            )) from exc
        case.with_context(**{
            AI_COLLECTIONS_EVIDENCE_CONTEXT:
                AI_COLLECTIONS_EVIDENCE_CAPABILITY,
        }).write({
            'eh_ai_suggestion_narrative': "%s (%s): %s" % (
                suggestion.action, suggestion.priority,
                suggestion.rationale,
            ),
            'eh_ai_narrative_generated_at': fields.Datetime.now(),
            'eh_ai_narrative_generated_by_id': self.env.user.id,
            'eh_ai_narrative_provider_key': provider_key,
            'eh_ai_narrative_source_fingerprint': fingerprint,
        })
        return True
