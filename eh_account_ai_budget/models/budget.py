"""
Live wiring of the budget-variance commentary onto eh.budget.budget.

The deterministic commentary is a non-stored computed field recomputed
on read so it always reflects the current line figures. The Odoo-
independent variance_commenter helper does the prose; this model only
builds the per-line snapshot and resolves the income flag from the
account type.

The optional LLM-enriched narrative is NEVER produced on read. A compute
must not perform synchronous network I/O: with a live provider configured
that would fire a blocking outbound HTTPS POST on every budget form/list
access and starve the HTTP workers. The provider is therefore invoked
only from the explicit action_eh_ai_refresh_commentary button, which
writes the result to a stored field.
"""

import hashlib
import json

from odoo import _, api, fields, models
from odoo.exceptions import AccessError, UserError
from odoo.tools.misc import format_amount

from odoo.addons.eh_account_ai_agent.tools import variance_commenter
from odoo.addons.eh_account_ai_agent.tools import provider_registry
from odoo.addons.eh_account_ai_agent.tools.provider_registry import ProviderError
from odoo.addons.eh_account_budget_pro.models.budget_report import (
    _INCOME_LIKE_ACCOUNT_TYPES,
)

# Exact credit-nature classification used by Budget Pro's normalised actuals.
# The commentary has a binary income-like/expense-like direction model, so it
# must use the same set that controls the sign flip.
_INCOME_TYPES = tuple(_INCOME_LIKE_ACCOUNT_TYPES)
_AI_NARRATIVE_CONTEXT = 'eh_ai_budget_narrative_capability'
_AI_NARRATIVE_CAPABILITY = object()
_AI_NARRATIVE_FIELDS = frozenset({
    'eh_ai_variance_narrative',
    'eh_ai_narrative_generated_at',
    'eh_ai_narrative_generated_by_id',
    'eh_ai_narrative_provider_key',
    'eh_ai_narrative_fingerprint',
})


class EhBudget(models.Model):
    _inherit = 'eh.budget.budget'

    eh_ai_variance_commentary = fields.Text(
        string="Variance commentary",
        compute='_compute_eh_ai_variance_commentary', store=False,
    )
    eh_ai_variance_narrative = fields.Text(
        string="AI variance narrative",
        readonly=True, copy=False,
        help="Provider-enriched narrative produced by the explicit "
             "Refresh AI commentary button. Empty until the button is "
             "pressed; never generated on read so budget access never "
             "triggers a synchronous LLM call.",
    )
    eh_ai_narrative_generated_at = fields.Datetime(
        string="AI narrative generated at", readonly=True, copy=False,
    )
    eh_ai_narrative_generated_by_id = fields.Many2one(
        'res.users', string="AI narrative generated by",
        readonly=True, copy=False,
    )
    eh_ai_narrative_provider_key = fields.Char(
        string="AI narrative provider", readonly=True, copy=False,
    )
    eh_ai_narrative_fingerprint = fields.Char(
        string="AI narrative source fingerprint",
        readonly=True, copy=False, index=True,
        help=(
            "SHA-256 of exact budget, account, period, budget, actual and "
            "provider configuration evidence used for this narrative."
        ),
    )
    eh_ai_narrative_stale = fields.Boolean(
        string="AI narrative is stale",
        compute='_compute_eh_ai_narrative_state',
    )
    eh_ai_live_provider_configured = fields.Boolean(
        compute='_compute_eh_ai_narrative_state',
    )

    @api.model_create_multi
    def create(self, vals_list):
        if any(_AI_NARRATIVE_FIELDS.intersection(vals) for vals in vals_list) \
                and self.env.context.get(_AI_NARRATIVE_CONTEXT) is not (
                    _AI_NARRATIVE_CAPABILITY
                ):
            raise AccessError(_(
                "AI narrative evidence is server-owned and cannot be "
                "supplied by a client."
            ))
        return super().create(vals_list)

    def write(self, vals):
        if _AI_NARRATIVE_FIELDS.intersection(vals) and (
            self.env.context.get(_AI_NARRATIVE_CONTEXT)
            is not _AI_NARRATIVE_CAPABILITY
        ):
            raise AccessError(_(
                "AI narrative evidence is server-owned and cannot be "
                "changed by a client."
            ))
        return super().write(vals)

    @api.depends(
        'name', 'line_ids',
        'line_ids.budgeted_amount', 'line_ids.actual_amount',
        'line_ids.account_id',
    )
    def _compute_eh_ai_variance_commentary(self):
        # DETERMINISTIC ONLY. Force the manual provider so the template
        # renders on every read/list without any network I/O; the
        # richer provider narrative is produced only by the explicit
        # action_eh_ai_refresh_commentary button below.
        for budget in self:
            snapshot = budget._eh_build_budget_snapshot()
            budget.eh_ai_variance_commentary = variance_commenter.comment(
                snapshot,
                period_label=budget.name or '',
                provider_key='manual',
                format_currency=lambda amount, budget=budget: format_amount(
                    budget.env, amount, budget.currency_id,
                ),
            )

    def _eh_build_budget_snapshot(self):
        """Map budget lines onto the helper's BudgetLineSnapshot records.

        is_income is resolved from the line account's account_type so
        the commentary describes an income shortfall and an expense
        overrun correctly rather than treating every variance the same.
        """
        self.ensure_one()
        snapshot = []
        for line in self.line_ids:
            account = line.account_id
            if not account:
                continue
            # Use the SIGN-NORMALISED actual, not the raw Odoo-signed balance.
            # actual_amount is a credit-negative SUM(balance); feeding it raw
            # made a fully-earned revenue line read as a ~200% miss
            # (-10000 - 10000). _normalised_actual() flips credit-natured
            # accounts so the figure reads in the same direction as the budget.
            snapshot.append(variance_commenter.BudgetLineSnapshot(
                label=account.display_name,
                budget=line.budgeted_amount or 0.0,
                actual=line._normalised_actual(),
                is_income=account.account_type in _INCOME_TYPES,
            ))
        return snapshot

    def _eh_ai_narrative_source_fingerprint(
        self, provider_key=None, provider_config=None,
    ):
        """Hash exact prompt facts without persisting provider secrets."""
        self.ensure_one()
        company = self.company_id.sudo()
        provider_key = provider_key or company.eh_ai_provider_key or 'manual'
        if provider_config is None:
            provider_config = company.eh_ai_provider_config or ''
        config_text = (
            provider_config if isinstance(provider_config, str)
            else json.dumps(provider_config or {}, sort_keys=True)
        )
        payload = {
            'schema': 1,
            'budget_id': self.id,
            'budget_name': self.name or '',
            'company_id': self.company_id.id,
            'currency_id': self.currency_id.id,
            'date_from': str(self.date_from or ''),
            'date_to': str(self.date_to or ''),
            'provider_key': provider_key,
            'provider_config_sha256': hashlib.sha256(
                config_text.encode('utf-8')
            ).hexdigest(),
            'lines': [
                {
                    'id': line.id,
                    'account_id': line.account_id.id,
                    'account_label': line.account_id.display_name,
                    'period_from': str(line.period_from or ''),
                    'period_to': str(line.period_to or ''),
                    'budget': line.budgeted_amount or 0.0,
                    'actual': line._normalised_actual(),
                    'is_income': (
                        line.account_id.account_type in _INCOME_TYPES
                    ),
                }
                for line in self.line_ids.sorted('id')
                if line.account_id
            ],
        }
        canonical = json.dumps(
            payload, sort_keys=True, separators=(',', ':'),
            ensure_ascii=False,
        ).encode('utf-8')
        return hashlib.sha256(canonical).hexdigest()

    @api.depends(
        'eh_ai_variance_narrative', 'eh_ai_narrative_fingerprint',
        'name', 'date_from', 'date_to', 'company_id', 'currency_id',
        'line_ids', 'line_ids.account_id', 'line_ids.period_from',
        'line_ids.period_to', 'line_ids.budgeted_amount',
        'line_ids.actual_amount',
    )
    def _compute_eh_ai_narrative_state(self):
        for budget in self:
            company = budget.company_id.sudo()
            provider_key = company.eh_ai_provider_key or 'manual'
            budget.eh_ai_live_provider_configured = bool(
                provider_key != 'manual'
                and provider_registry.has_provider(provider_key)
            )
            budget.eh_ai_narrative_stale = bool(
                budget.eh_ai_variance_narrative
                and budget.eh_ai_narrative_fingerprint
                != budget._eh_ai_narrative_source_fingerprint(
                    provider_key=provider_key,
                    provider_config=company.eh_ai_provider_config or '',
                )
            )

    def action_eh_ai_refresh_commentary(self):
        """Explicit user gesture that runs the configured AI provider.

        This is the ONLY place the provider is invoked, because the
        provider may perform outbound network I/O (a blocking HTTPS
        POST). Running it here, on a deliberate button press, keeps that
        call off the read path: budget forms and lists render the
        deterministic compute field without ever touching the network.
        The provider-enriched text is written to the stored
        eh_ai_variance_narrative field. A missing, manual, failed, or empty
        provider raises a user-facing error and leaves any existing narrative
        unchanged; deterministic commentary is never relabelled as AI output.
        """
        # This public RPC can disclose provider credentials through sudo and
        # incur network cost.  Prove the caller may mutate every target
        # budget before reading the secret configuration or invoking it.
        self._eh_check_access('write')
        prepared = []
        for budget in self:
            snapshot = budget._eh_build_budget_snapshot()
            company = budget.company_id
            company_config = company.sudo()
            provider_key = company_config.eh_ai_provider_key or 'manual'
            provider_config = company_config.eh_ai_provider_config or None
            fingerprint = budget._eh_ai_narrative_source_fingerprint(
                provider_key=provider_key,
                provider_config=provider_config or '',
            )
            # Exact snapshot/provider cache: repeated presses must not incur a
            # second provider charge for bytes already stored and attributed.
            if (
                budget.eh_ai_variance_narrative
                and budget.eh_ai_narrative_fingerprint == fingerprint
                and budget.eh_ai_narrative_provider_key == provider_key
            ):
                continue
            try:
                narrative = variance_commenter.provider_comment(
                    snapshot,
                    period_label=budget.name or '',
                    provider_key=provider_key,
                    provider_config=provider_config,
                    format_currency=lambda amount, budget=budget: (
                        format_amount(
                            budget.env, amount, budget.currency_id,
                        )
                    ),
                )
            except ProviderError as exc:
                raise UserError(_(
                    "No AI narrative was stored: %(reason)s The existing "
                    "narrative, if any, is unchanged.",
                    reason=str(exc),
                )) from exc
            prepared.append((
                budget, narrative, provider_key, provider_config or '',
                fingerprint,
            ))

        # Provider calls above run without business-row locks. Lock and
        # re-prove prompt facts only after every remote response is ready, so
        # multi-budget refreshes never hold earlier budget locks across later
        # HTTP calls and never persist output for a concurrently changed basis.
        if prepared:
            budget_ids = sorted(budget.id for budget, *_rest in prepared)
            self.env.cr.execute(
                "SELECT id FROM eh_budget_budget WHERE id = ANY(%s) "
                "ORDER BY id FOR UPDATE",
                [budget_ids],
            )
            self.env.cr.execute(
                "SELECT id FROM eh_budget_line WHERE budget_id = ANY(%s) "
                "ORDER BY id FOR UPDATE",
                [budget_ids],
            )
        for budget, narrative, provider_key, provider_config, fingerprint \
                in prepared:
            budget.invalidate_recordset([
                'name', 'date_from', 'date_to', 'company_id', 'currency_id',
                'line_ids',
            ])
            budget.line_ids.invalidate_recordset([
                'account_id', 'period_from', 'period_to',
                'budgeted_amount', 'actual_amount',
            ])
            budget.company_id.sudo().invalidate_recordset([
                'eh_ai_provider_key', 'eh_ai_provider_config',
            ])
            current_company = budget.company_id.sudo()
            current_provider = current_company.eh_ai_provider_key or 'manual'
            current_config = current_company.eh_ai_provider_config or ''
            if (
                current_provider != provider_key
                or current_config != provider_config
                or budget._eh_ai_narrative_source_fingerprint(
                    provider_key=current_provider,
                    provider_config=current_config,
                ) != fingerprint
            ):
                raise UserError(_(
                    "Budget or provider configuration changed while AI "
                    "commentary was being generated. Nothing was stored; "
                    "review the changes and refresh again."
                ))
            budget.with_context(**{
                _AI_NARRATIVE_CONTEXT: _AI_NARRATIVE_CAPABILITY,
            }).write({
                'eh_ai_variance_narrative': narrative,
                'eh_ai_narrative_generated_at': fields.Datetime.now(),
                'eh_ai_narrative_generated_by_id': self.env.user.id,
                'eh_ai_narrative_provider_key': provider_key,
                'eh_ai_narrative_fingerprint': fingerprint,
            })
        return True
