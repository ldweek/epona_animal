"""Purge unprovable draft exports left by pre-integrity workflow versions."""

from odoo import SUPERUSER_ID, api


def migrate(cr, version):
    if not version:
        return
    env = api.Environment(cr, SUPERUSER_ID, {})
    env['eh.batch.payment']._eh_quarantine_legacy_integrity()
